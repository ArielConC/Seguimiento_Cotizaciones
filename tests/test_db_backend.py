from __future__ import annotations

import unittest

import db_backend


class SQLTranslationTests(unittest.TestCase):
    def test_parameters_do_not_change_question_marks_inside_strings(self):
        translated = db_backend.translate_sql("SELECT '?' AS literal,value FROM settings WHERE key=?")
        self.assertEqual(translated, "SELECT '?' AS literal,value FROM settings WHERE key=%s")

    def test_sqlite_identity_is_postgresql_identity(self):
        translated = db_backend.translate_sql("id INTEGER PRIMARY KEY AUTOINCREMENT")
        self.assertEqual(translated, "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")

    def test_sqlite_real_keeps_double_precision(self):
        translated = db_backend.translate_sql("total_usd REAL NOT NULL, source_mtime REAL")
        self.assertEqual(
            translated,
            "total_usd DOUBLE PRECISION NOT NULL, source_mtime DOUBLE PRECISION",
        )

    def test_insert_or_ignore_uses_conflict_clause(self):
        translated = db_backend.translate_sql("INSERT OR IGNORE INTO settings(key,value) VALUES(?,?)")
        self.assertEqual(
            translated,
            "INSERT INTO settings(key,value) VALUES(%s,%s) ON CONFLICT DO NOTHING",
        )

    def test_nocase_comparison_uses_lower(self):
        translated = db_backend.translate_sql("SELECT * FROM users WHERE username=? COLLATE NOCASE")
        self.assertEqual(translated, "SELECT * FROM users WHERE LOWER(username)=LOWER(%s)")

    def test_sqlite_date_helpers_are_translated(self):
        translated = db_backend.translate_sql(
            "SELECT datetime(COALESCE(updated_at,created_at)),instr(folio,'-'),date(discovered_at) FROM quotes"
        )
        self.assertIn("(COALESCE(updated_at,created_at))", translated)
        self.assertIn("strpos(folio,'-')", translated)
        self.assertNotIn("datetime", translated.casefold())
        self.assertIn("substr(discovered_at,1,10)", translated)

    def test_boolean_sum_is_portable(self):
        translated = db_backend.translate_sql("SELECT SUM(status='pending') FROM quotes")
        self.assertEqual(
            translated,
            "SELECT SUM(CASE WHEN status='pending' THEN 1 ELSE 0 END) FROM quotes",
        )

    def test_immediate_transactions_use_a_postgresql_transaction_lock(self):
        translated = db_backend.translate_sql("BEGIN IMMEDIATE")
        self.assertEqual(translated, "SELECT pg_advisory_xact_lock(68421573)")

    def test_scripts_split_only_on_unquoted_semicolons(self):
        statements = db_backend.split_script("INSERT INTO t(v) VALUES('a;b'); SELECT 1;")
        self.assertEqual(statements, ["INSERT INTO t(v) VALUES('a;b')", "SELECT 1"])

    def test_hybrid_row_supports_sqlite_row_patterns(self):
        row = db_backend.HybridRow(("id", "name"), (7, "Ariel"))
        self.assertEqual(row[0], 7)
        self.assertEqual(row["name"], "Ariel")
        self.assertEqual(dict(row), {"id": 7, "name": "Ariel"})

    def test_literal_percent_signs_are_escaped_for_psycopg(self):
        translated = db_backend.translate_sql("SELECT 1 FROM t WHERE reason NOT LIKE 'Merged duplicate%' AND id=?")
        self.assertEqual(translated, "SELECT 1 FROM t WHERE reason NOT ILIKE 'Merged duplicate%%' AND id=%s")

    def test_like_searches_stay_case_insensitive(self):
        translated = db_backend.translate_sql("SELECT * FROM quotes WHERE end_user LIKE ?")
        self.assertEqual(translated, "SELECT * FROM quotes WHERE end_user ILIKE %s")


if __name__ == "__main__":
    unittest.main()
